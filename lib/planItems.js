/**
 * รหัสสินค้าฝั่ง POS เก็บเลข 0 นำหน้าบ้างไม่เก็บบ้าง (แอปสั่งของของสาขาก็ตัดทิ้งตอนจับคู่เหมือนกัน)
 * เทียบกันตรง ๆ จะพลาด — ตัด 0 นำหน้ากับช่องว่างออกก่อนเสมอ
 */
export const normItemCode = v => String(v ?? '').trim().replace(/^0+/, '');

export const STATUS_ACTIVE = 'active';
export const STATUS_INACTIVE = 'inactive';

/** ตรวจรหัสก่อนบันทึก — คืนข้อความบอกที่ผิด หรือ '' ถ้าใช้ได้ */
export function validateItemCode(code) {
  const c = normItemCode(code);
  if (!c) return 'ต้องใส่รหัสสินค้า';
  if (!/^[0-9]+$/.test(c)) return 'รหัสสินค้าฝั่ง POS เป็นตัวเลขล้วน';
  if (c.length > 32) return 'รหัสสินค้ายาวเกินไป';
  return '';
}

/**
 * ตัวเช็คว่าอยู่ในหมวดแพลนไหม จากรายชื่อที่โหลดมาจากฐาน
 * (นับเฉพาะตัวที่ยังเปิดใช้งาน — ตัวที่ปิดไว้ถือว่าไม่อยู่ในแพลนแล้ว)
 */
export function makePlanMatcher(items) {
  const set = new Set(
    (items || [])
      .filter(i => (i.status || STATUS_ACTIVE) !== STATUS_INACTIVE)
      .map(i => normItemCode(i.code))
      .filter(Boolean)
  );
  return code => set.has(normItemCode(code));
}
