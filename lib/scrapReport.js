/** ตัด .0 ท้าย + 0 นำหน้า ให้รหัสจาก POS จับคู่กันได้ (แบบเดียวกับ lib/usageRules.js) */
export const normCode = id => String(id ?? '').trim().replace(/\.0+$/, '').replace(/^0+/, '');

/**
 * คีย์เทียบชื่อไอเทมในใบเบิก — ตัดช่องว่างและเครื่องหมายวรรคตอนทิ้งทั้งหมด
 * ชื่อในระบบ inventory พิมพ์เว้นวรรค/จุดไม่เหมือนกันทุกครั้ง (เช่น "กก." กับ "กก")
 * เทียบตรงตัวอักษรจะหลุดง่าย
 */
export const nameKey = name =>
  String(name ?? '').toLowerCase().replace(/[\s.,()\/\\\-_+]/g, '');

/** รหัส POS -> { kind: 'scrap' | 'prep', group: รหัสเศษ, name } */
export const POS_CODE_MAP = (() => {
  const map = {};
  SCRAP_GROUPS.forEach(g => {
    map[g.code] = { kind: 'scrap', group: g.code, name: g.name };
    g.preps.forEach(p => { map[p.code] = { kind: 'prep', group: g.code, name: p.name }; });
  });
  return map;
})();

/** คีย์ชื่อไอเทมต้นทาง -> { group: รหัสเศษ, name: ชื่อที่ใช้แสดง } */
export const SOURCE_NAME_MAP = (() => {
  const map = {};
  SCRAP_GROUPS.forEach(g => g.sources.forEach(n => { map[nameKey(n)] = { group: g.code, name: n }; }));
  return map;
})();
