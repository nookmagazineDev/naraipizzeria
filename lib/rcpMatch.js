// ต้องคิดคีย์ด้วยสูตรเดียวกันเป๊ะ ไม่งั้นเก็บลงฐานแบบหนึ่ง ค้นอีกแบบหนึ่ง แล้วไม่เจอกันเงียบ ๆ
// เหมือนที่ normItemCode ใน lib/planItems.js เป็นตัวเดียวกันทั้งฝั่งเว็บและฝั่งฐาน
//
// ⚠️ ทำไมต้อง normalize แรงขนาดนี้ — สองชีทสะกดของสิ่งเดียวกันไม่ตรงกันจริง
//      8.2 เขียน  FCเนยกระเทียม (1ถุง/1กก) กก.      RcpDtls เขียน  FC ชีสพิซซ่า (0.4กก./ถุง)ถุง
//      บ้างเว้นวรรคหลัง FC บ้างไม่เว้น · วงเล็บและจุดคั่นไม่เหมือนกัน · หน่วยท้ายชื่อเขียนคนละแบบ
//    เทียบชื่อดิบ ๆ จะหลุดเกินครึ่งโดยไม่มีอะไรฟ้อง
//
// ⚠️ แต่ "ไม่" ตัดวรรณยุกต์ออกจากคีย์หลัก ทั้งที่ทำแล้วจับคู่ได้เยอะขึ้น
//    เพราะ ซีอิ้ว/ซีอิ๊ว กับ แพ็ค/แพ๊ค เป็นคำเดียวกันก็จริง แต่ตัดวรรณยุกต์ทิ้งทั้งชุด
//    ทำให้ของคนละตัวชนกันได้ด้วย การเอาสูตรผิดไปแปะเมนูแย่กว่าการไม่มีสูตรให้ดู
//    ตัวตัดวรรณยุกต์จึงแยกไว้เป็น rcpNameKeyLoose ใช้เฉพาะตอน "รายงานว่าน่าจะใช่ตัวไหน"
//    ไม่เอาไปใช้แปะสูตรอัตโนมัติ

/** คีย์หลัก — ใช้ตัดสินว่าเมนูนี้กับสูตรนี้เป็นตัวเดียวกัน */
export const rcpNameKey = (v) => String(v ?? '')
  .normalize('NFC')
  .replace(/[\s ]+/g, '')        // ช่องว่างทุกชนิด รวม non-breaking space ที่ติดมาจาก Excel
  .replace(/[()[\]{}]/g, '')          // วงเล็บ (ขนาดบรรจุ)
  .replace(/[.,;:'"`\/\\_-]/g, '')    // เครื่องหมายคั่น
  .toLowerCase();

// วรรณยุกต์/ไม้ไต่คู้/การันต์ไทย U+0E47–U+0E4E
const THAI_TONE = /[็-๎]/g;

/** คีย์หลวม — ใช้ "เสนอ" ว่าน่าจะใช่ตัวไหนเท่านั้น ห้ามเอาไปแปะสูตรเอง */
export const rcpNameKeyLoose = (v) => rcpNameKey(v).replace(THAI_TONE, '');

/** รหัสวัตถุดิบ — ตัด 0 นำหน้าและ .0 ท้าย ให้ตรงกับธรรมเนียม item_key ของตาราง stock_* */
export const rcpItemKey = (v) => String(v ?? '')
  .trim()
  .replace(/\.0+$/, '')
  .replace(/^0+/, '')
  .toLowerCase();

/** ชื่อตาราง — เขียนที่เดียว กันสคริปต์กับ API พิมพ์ไม่ตรงกัน */
export const RCP_RECIPE_TABLE = 'dbo.rcp_recipe';
export const RCP_LINE_TABLE = 'dbo.rcp_line';
