// ชื่อเดือน/วันที่ภาษาไทย — ที่เดียวของทั้งเว็บ ไม่งั้นแต่ละหน้าย่อเดือนไม่เหมือนกัน
//
// ปีที่แสดงเป็น พ.ศ. เสมอ ตามที่ออฟฟิศเรียกกัน (ข้อมูลที่เก็บยังเป็น ค.ศ. ทุกที่ ไม่ได้แปลงตาม)
// ตัวย่อใช้ของราชบัณฑิตฯ (ม.ค. ก.พ. มี.ค. …) ไม่ใช่การตัดตัวอักษร 3 ตัวแรกของชื่อเต็ม
// ซึ่งได้ "สิง." "กัน." ที่ไม่มีใครเขียนกัน
export const TH_MONTHS = ['มกราคม', 'กุมภาพันธ์', 'มีนาคม', 'เมษายน', 'พฤษภาคม', 'มิถุนายน',
  'กรกฎาคม', 'สิงหาคม', 'กันยายน', 'ตุลาคม', 'พฤศจิกายน', 'ธันวาคม'];

export const TH_MONTHS_SHORT = ['ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.',
  'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.'];

/** 'YYYY-MM' -> 'สิงหาคม 2569' (รูปแบบไม่ตรงก็คืนของเดิม ไม่ใช่ขึ้น NaN) */
export function monthLabel(ym) {
  const m = /^(\d{4})-(\d{2})/.exec(String(ym || ''));
  return m ? `${TH_MONTHS[Number(m[2]) - 1] || m[2]} ${Number(m[1]) + 543}` : String(ym || '');
}

/** 'YYYY-MM-DD' -> '31 ส.ค. 69' */
export function dateLabel(iso) {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(iso || ''));
  if (!m) return String(iso || '-');
  return `${Number(m[3])} ${TH_MONTHS_SHORT[Number(m[2]) - 1] || m[2]} ${String(Number(m[1]) + 543).slice(-2)}`;
}
